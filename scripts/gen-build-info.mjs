#!/usr/bin/env node
/**
 * scripts/gen-build-info.mjs — bake the SemText asset-URL inputs into
 * data/semtext-build-info.ts.
 *
 *   node scripts/gen-build-info.mjs
 *
 * Two constants:
 *   SEMTEXT_VERSION — the stable version from the vendored
 *                     app/backend/priv/static/semtext/versions.json
 *                     (written by scripts/sync-bundles.mjs). A consumer
 *                     pins /semtext/v<SEMTEXT_VERSION>/… — the immutable,
 *                     version-addressed snapshot the last sync published.
 *   BUILD_EPOCH     — this build's unix seconds. Appended as ?v= to every
 *                     pinned URL, so a deploy revalidates its bundle URLs
 *                     even when SEMTEXT_VERSION is unchanged (belt and
 *                     braces on top of the immutable path).
 *
 * History: this ran as the Next.js site's `prebuild` and wrote
 * web/lib/semtext-build-info.ts for web/lib/semtext-asset.ts. The web/
 * tree was retired 2026-11-11; the Hologram app pins its bundle versions
 * directly in its pages (e.g. editor_page.ex). The generator is retained
 * as the one place that reads the synced stable version, for any future
 * pinning consumer. The generated file is COMMITTED; every run regenerates
 * it, and a diff means the pinned version moved.
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const versionsPath = resolve(repoRoot, 'app', 'backend', 'priv', 'static', 'semtext', 'versions.json');
const outPath = resolve(repoRoot, 'data', 'semtext-build-info.ts');

if (!existsSync(versionsPath)) {
  console.error(
    'gen-build-info: app/backend/priv/static/semtext/versions.json missing — run scripts/sync-bundles.mjs first (see its header).',
  );
  process.exit(1);
}
let stable;
try {
  stable = JSON.parse(readFileSync(versionsPath, 'utf8')).stable;
} catch {
  stable = null;
}
if (!stable) {
  console.error('gen-build-info: versions.json has no "stable" version — sync a final release first.');
  process.exit(1);
}

const epoch = Math.floor(Date.now() / 1000);
writeFileSync(
  outPath,
  [
    '/* Generated by scripts/gen-build-info.mjs — committed, but regenerated on',
    ' * every run. Do not edit by hand: re-run the generator or re-sync bundles.',
    ' * The retired Next site consumed this via web/lib/semtext-asset.ts; the',
    ' * Hologram app pins bundle versions in its pages. */',
    '',
    `export const SEMTEXT_VERSION = ${JSON.stringify(stable)};`,
    `export const BUILD_EPOCH = ${JSON.stringify(String(epoch))};`,
    '',
  ].join('\n'),
);
console.log(`gen-build-info: data/semtext-build-info.ts (stable ${stable}, epoch ${epoch})`);
