#!/usr/bin/env node
/**
 * scripts/gen-build-info.mjs — bake the SemText asset-URL inputs into
 * lib/semtext-build-info.ts at build time.
 *
 *   node scripts/gen-build-info.mjs        (wired as the `prebuild` npm
 *                                           script; runs before `next build`)
 *
 * Two constants:
 *   SEMTEXT_VERSION — the stable version from public/semtext/versions.json
 *                     (written by scripts/sync-bundles.mjs). Pages pin
 *                     /semtext/v<SEMTEXT_VERSION>/… — the immutable,
 *                     version-addressed snapshot the last sync published.
 *   BUILD_EPOCH     — this site build's unix seconds. Appended as ?v= to
 *                     every pinned URL, so a site deploy revalidates its
 *                     bundle URLs even when SEMTEXT_VERSION is unchanged
 *                     (belt and braces on top of the immutable path).
 *
 * The generated file is COMMITTED: `next dev` (the snap harness, local
 * work) never runs prebuild, and CI orderings stay boring. Every build
 * regenerates it; a diff in a PR means the pinned version moved.
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const versionsPath = resolve(webRoot, 'public', 'semtext', 'versions.json');
const outPath = resolve(webRoot, 'lib', 'semtext-build-info.ts');

if (!existsSync(versionsPath)) {
  console.error(
    'gen-build-info: public/semtext/versions.json missing — run scripts/sync-bundles.mjs first (see its header).',
  );
  process.exit(1);
}
let stable;
try {
  stable = JSON.parse(readFileSync(versionsPath, 'utf8')).stable;
} catch {
  stable = null;
}
if (!stable) {
  console.error('gen-build-info: public/semtext/versions.json has no "stable" version — sync a final release first.');
  process.exit(1);
}

const epoch = Math.floor(Date.now() / 1000);
writeFileSync(
  outPath,
  [
    '/* Generated by scripts/gen-build-info.mjs — committed, but regenerated on',
    ' * every `next build` (prebuild). Do not edit by hand: re-run the generator',
    ' * or re-sync bundles. See lib/semtext-asset.ts for the URL helpers that',
    ' * consume these constants. */',
    '',
    `export const SEMTEXT_VERSION = ${JSON.stringify(stable)};`,
    `export const BUILD_EPOCH = ${JSON.stringify(String(epoch))};`,
    '',
  ].join('\n'),
);
console.log(`gen-build-info: lib/semtext-build-info.ts (stable ${stable}, epoch ${epoch})`);
