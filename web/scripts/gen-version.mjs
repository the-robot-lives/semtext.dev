/**
 * scripts/gen-version.mjs — cache-bust token for every URL that loads one
 * of the SemText bundles this landing page ships (runs as `npm run
 * prebuild`, before `next build`).
 *
 * The token is a content hash (sha256, 16 hex chars) over everything the
 * browser fetches from public/semtext/ and the dataviz reading bundle:
 * deterministic for a given code state, and it rotates the moment any
 * artifact byte changes — so a page never resolves to a stale cached
 * bundle, and semtext-lazy.js forwards the same v= to every chunk it
 * imports (see the loader patch recorded in public/semtext/VERSION.md).
 *
 * Output: lib/semtext-version.ts — a plain module both server and client
 * components import. Committed so `next dev` works without a prebuild;
 * regenerated on every `npm run build`.
 */
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function hashTree(hash, dir) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir).sort()) {
    if (name.endsWith(".md")) continue; // prose, not fetched by a bundle URL
    const p = resolve(dir, name);
    if (statSync(p).isDirectory()) hashTree(hash, p);
    else {
      hash.update(name);
      hash.update(readFileSync(p));
    }
  }
}

const hash = createHash("sha256");
hashTree(hash, resolve(webRoot, "public/semtext"));
for (const f of ["dataviz/semtext-reading.js"]) {
  const p = resolve(webRoot, "public", f);
  if (existsSync(p)) {
    hash.update(f);
    hash.update(readFileSync(p));
  }
}
const version = hash.digest("hex").slice(0, 16);

const out = resolve(webRoot, "lib/semtext-version.ts");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `/** GENERATED by scripts/gen-version.mjs (npm run prebuild) — do not edit by hand.
 *  Content hash of every bundle under public/semtext/ (+ the dataviz reading
 *  bundle). Appended as ?v= to each bundle URL so browsers never serve a
 *  stale build; semtext-lazy.js passes the same v= on to the chunks it
 *  imports. */
export const SEMTEXT_VERSION = "${version}";
`,
);
console.log(`gen-version: SEMTEXT_VERSION=${version} → lib/semtext-version.ts`);
