/*
 * The index of the reference section: a short intro, the two families,
 * and a card per element linking to its own page at /reference/<tag>/.
 * Pure server component — every card is in the static HTML; the filter
 * box below only narrows what is already rendered, so the default view
 * needs no JavaScript.
 *
 * The tag data comes verbatim from data/elements.json (generated by
 * scripts/build-elements-index.mjs in noizu-labs-ml/npl-enhanced-content
 * from spec/schema/sem-*.md and spec/schema/npl/*.md — never hand-edit
 * the JSON) plus the hand-authored supplement for the eight elements the
 * generator cannot emit. Each element's options, children and example
 * live on its own page.
 */

/*
 * One small vanilla script, as on the landing page: the input narrows the
 * element cards and the sidebar links by tag name or summary. With no JS
 * nothing runs and the page shows every element — the static render is
 * whole.
 */
const FILTER_SCRIPT = `(function(){
  function ready(fn){ if(document.readyState!=="loading"){fn();}else{document.addEventListener("DOMContentLoaded",fn);} }
  ready(function(){
    var input=document.getElementById("ref-search");
    if(!input){return;}
    var cards=document.querySelectorAll("main a[data-ref-tag]");
    function linkTarget(a){return a.getAttribute("data-ref")||"";}
    var links=[].slice.call(document.querySelectorAll('nav[aria-label="Docs"] a[data-ref]'));
    var count=document.getElementById("ref-count");
    function apply(){
      var q=input.value.trim().toLowerCase();
      var shown=0;
      for(var i=0;i<cards.length;i++){
        var el=cards[i];
        el.hidden=q.length>0&&el.getAttribute("data-ref").indexOf(q)===-1;
        if(!el.hidden){shown++;}
      }
      for(var j=0;j<links.length;j++){
        var a=links[j];
        a.hidden=q.length>0&&linkTarget(a).indexOf(q)===-1;
      }
      if(count){count.textContent=q.length>0?shown+" of "+cards.length+" tags":"";
        count.hidden=q.length===0;}
    }
    input.addEventListener("input",apply);
  });
})();`;

