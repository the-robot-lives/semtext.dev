import type { Metadata } from "next";
import { DocsShell } from "@/components/docs-shell";
import type { TagRecord } from "@/data/reference-glossary";
import {
  GAP_MISSING,
  NPL_TAGS,
  SEM_TAGS,
  SPEC_VERSION,
  tagHref,
} from "@/data/reference-tags";

export const metadata: Metadata = {
  title: "Reference — every SemText and NPL tag",
  description:
    "Generated reference for every SemText (sem-*) and NPL (npl-) tag: options, children and an authored example, one page per element, built from the spec's schema files.",
  alternates: { canonical: "https://semtext.dev/reference/" },
};

/*
 * The index of the reference section: a short intro, the two families,
 * and a card per element linking to its own page at /reference/<tag>/.
 * Pure server component — every card is in the static HTML; the filter
 * box below only narrows what is already rendered, so the default view
 * needs no JavaScript.
 *
 * The tag data comes verbatim from data/elements.json (generated by
 * scripts/build-elements-index.mjs in noizu-labs-ml/npl-enhanced-content
 * from spec/schema/sem-*.md and spec/schema/npl/*.md — never hand-edit
 * the JSON) plus the hand-authored supplement for the eight elements the
 * generator cannot emit. Each element's options, children and example
 * live on its own page.
 */

/*
 * One small vanilla script, as on the landing page: the input narrows the
 * element cards and the sidebar links by tag name or summary. With no JS
 * nothing runs and the page shows every element — the static render is
 * whole.
 */
const FILTER_SCRIPT = `(function(){
  function ready(fn){ if(document.readyState!=="loading"){fn();}else{document.addEventListener("DOMContentLoaded",fn);} }
  ready(function(){
    var input=document.getElementById("ref-search");
    if(!input){return;}
    var cards=document.querySelectorAll("main a[data-ref-tag]");
    function linkTarget(a){return a.getAttribute("data-ref")||"";}
    var links=[].slice.call(document.querySelectorAll('nav[aria-label="Docs"] a[data-ref]'));
    var count=document.getElementById("ref-count");
    function apply(){
      var q=input.value.trim().toLowerCase();
      var shown=0;
      for(var i=0;i<cards.length;i++){
        var el=cards[i];
        el.hidden=q.length>0&&el.getAttribute("data-ref").indexOf(q)===-1;
        if(!el.hidden){shown++;}
      }
      for(var j=0;j<links.length;j++){
        var a=links[j];
        a.hidden=q.length>0&&linkTarget(a).indexOf(q)===-1;
      }
      if(count){count.textContent=q.length>0?shown+" of "+cards.length+" tags":"";
        count.hidden=q.length===0;}
    }
    input.addEventListener("input",apply);
  });
})();`;

const FAMILIES: Array<{
  family: TagRecord["family"];
  title: string;
  blurb: string;
  tags: TagRecord[];
}> = [
  {
    family: "sem",
    title: "SemText elements",
    blurb:
      "The sem-* XHTML vocabulary — the document-shaped format every SemText consumer reads.",
    tags: SEM_TAGS,
  },
  {
    family: "npl",
    title: "NPL elements",
    blurb:
      "The npl-* components — display renders of NPL prompt blocks (agent introspection, critique, reasoning).",
    tags: NPL_TAGS,
  },
];

export default function ReferencePage() {
  const familyGroup = (title: string, tags: TagRecord[]) => ({
    title,
    items: tags.map((t) => ({
      key: `ref-${t.name}`,
      label: t.name,
      href: tagHref(t.name),
      dataRef: `${t.name} ${t.summary}`.toLowerCase(),
    })),
  });

  const groups = [
    { title: "Guides", items: [{ key: "cli", label: "CLI commands", href: "/docs/" }] },
    { title: "Reference", items: [
      { key: "reference", label: "Tag reference", href: "/reference/" },
    ] },
    familyGroup("SemText elements", SEM_TAGS),
    familyGroup("NPL elements", NPL_TAGS),
  ];

  return (
    <DocsShell active="reference" groups={groups}>
      <main id="main">
        <p className="g-eyebrow">Reference</p>
        <h1 className="mt-2 text-3xl font-semibold tracking-tight text-ink sm:text-4xl">
          Every tag, on its own page
        </h1>
        <p className="mt-4 max-w-3xl text-base leading-7 text-ink-mute">
          All {SEM_TAGS.length + NPL_TAGS.length} SemText and NPL tags, each
          with its options, children and an authored example on its own page
          — generated from the normative schema files of spec v{SPEC_VERSION}
          {" "}(<code className="font-mono">spec/schema/sem-*.md</code>,{" "}
          <code className="font-mono">spec/schema/npl/*.md</code>), so the
          pages cannot drift from the spec. Eight elements the schema files
          do not cover come from the spec&apos;s tag catalog instead
          (<code className="font-mono">spec/conventions.md</code>,{" "}
          <code className="font-mono">spec/schema/sem-facts.md</code>).
          Fields a source does not state stay empty and the element&apos;s
          page marks them.
        </p>

        <div className="mt-8 max-w-3xl">
          <label htmlFor="ref-search" className="g-nav-title">
            Filter tags
          </label>
          <input
            id="ref-search"
            type="search"
            placeholder="Type a tag name or a summary word — e.g. quiz, chronology, agent"
            autoComplete="off"
            className="mt-2 w-full rounded-md border border-white/15 bg-white/5 px-3 py-2 font-mono text-sm text-ink placeholder:text-ink-faint focus:border-white/40 focus:outline-none"
          />
          <p id="ref-count" hidden className="mt-2 text-sm text-ink-mute" aria-live="polite" />
        </div>

        {FAMILIES.map(({ family, title, blurb, tags }) => (
          <section
            key={family}
            aria-labelledby={`family-${family}-h`}
            className="mt-14"
          >
            <h2
              id={`family-${family}-h`}
              className="text-2xl font-semibold tracking-tight text-ink"
            >
              {title}
            </h2>
            <p className="mt-3 max-w-3xl leading-relaxed text-ink-mute">{blurb}</p>
            <div className="mt-6 grid gap-3 sm:grid-cols-2">
              {tags.map((t) => (
                <TagCard key={t.name} tag={t} />
              ))}
            </div>
          </section>
        ))}

        <script defer dangerouslySetInnerHTML={{ __html: FILTER_SCRIPT }} />
      </main>
    </DocsShell>
  );
}

function TagCard({ tag: t }: { tag: TagRecord }) {
  const missing = GAP_MISSING.get(t.name) ?? [];
  const gapNote = missing.includes("summary") || missing.includes("description");

  return (
    <a
      href={tagHref(t.name)}
      data-ref-tag={t.name}
      data-ref={`${t.name} ${t.summary}`.toLowerCase()}
      className="group rounded-lg border border-white/10 bg-white/[0.03] px-4 py-3.5 transition-colors hover:border-white/30 hover:bg-white/[0.06]"
    >
      <span className="flex items-baseline justify-between gap-2">
        <code className="font-mono text-sm text-ink group-hover:text-white">
          &lt;{t.name}&gt;
        </code>
        <span className="shrink-0 text-[0.62rem] font-normal uppercase tracking-wide text-ink-faint">
          {t.family === "sem" ? "SemText" : "NPL"}
        </span>
      </span>
      {t.summary ? (
        <span className="mt-1.5 block text-sm leading-6 text-ink-mute">
          {t.summary}
        </span>
      ) : gapNote ? (
        <span className="mt-1.5 block text-sm italic leading-6 text-ink-faint">
          No summary stated — the schema file marks the gap.
        </span>
      ) : (
        <span className="mt-1.5 block text-sm italic leading-6 text-ink-faint">
          See the element&apos;s page.
        </span>
      )}
    </a>
  );
}
