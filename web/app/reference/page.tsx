function TagCard({ tag: t }: { tag: TagRecord }) {
  const missing = GAP_MISSING.get(t.name) ?? [];
  const gapNote = missing.includes("summary") || missing.includes("description");

  return (
    <a
      href={tagHref(t.name)}
      data-ref-tag={t.name}
      data-ref={`${t.name} ${t.summary}`.toLowerCase()}
      className="group rounded-lg border border-white/10 bg-white/[0.03] px-4 py-3.5 transition-colors hover:border-white/30 hover:bg-white/[0.06]"
    >
      <span className="flex items-baseline justify-between gap-2">
        <code className="font-mono text-sm text-ink group-hover:text-white">
          &lt;{t.name}&gt;
        </code>
        <span className="shrink-0 text-[0.62rem] font-normal uppercase tracking-wide text-ink-faint">
          {t.family === "sem" ? "SemText" : "NPL"}
        </span>
      </span>
      {t.summary ? (
        <span className="mt-1.5 block text-sm leading-6 text-ink-mute">
          {t.summary}
        </span>
      ) : gapNote ? (
        <span className="mt-1.5 block text-sm italic leading-6 text-ink-faint">
          No summary stated — the schema file marks the gap.
        </span>
      ) : (
        <span className="mt-1.5 block text-sm italic leading-6 text-ink-faint">
          See the element&apos;s page.
        </span>
      )}
      <BundleBadge name={t.name} family={t.family} />
    </a>
  );
}

/*
 * Compact shipped-runtime badge: the file that provides the element (the
 * lazy chunk when one exists, else the fallback bundle), a fallback suffix
 * when the enhancement tier also covers it, or an honest none. The title
 * carries the full provenance. Derived from data/bundles.json — never
 * hand-maintained.
 */
function BundleBadge({
  name,
  family,
}: {
  name: string;
  family: TagRecord["family"];
}) {
  const b = bundlesFor(name);
  if (!b) return null;
  let text: string;
  let title: string;
  if (family === "npl" || !b.shipped) {
    text = family === "npl" ? "not in site bundles" : "no shipped runtime";
    title = b.note ?? "";
  } else {
    const files = b.bundles ?? [];
    const lazy = files.find((f) => f.file === "semtext-lazy.js");
    const chunk = lazy?.detail.replace(/^loads\s+/, "");
    text = [
      chunk ?? files[0]?.file,
      files.some((f) => f.file === "semtext-fallback.js") ? "fallback" : null,
    ]
      .filter((x): x is string => Boolean(x))
      .join(" · ");
    title =
      (b.sharedWith ? `same runtime as ${b.sharedWith}: ` : "") +
      files.map((f) => f.file).join(" + ");
  }
  return (
    <span
      title={title}
      className="mt-2.5 block truncate font-mono text-[0.62rem] text-ink-faint"
    >
      {text}
    </span>
  );
}
