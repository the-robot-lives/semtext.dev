/*
 * Pure server component. Every tag section is in the static HTML — the
 * filter box below only narrows what is already rendered, so the default
 * view needs no JavaScript.
 *
 * The tag data comes verbatim from data/elements.json, generated by
 * scripts/build-elements-index.mjs in noizu-labs-ml/npl-enhanced-content
 * from spec/schema/sem-*.md and spec/schema/npl/*.md. Never hand-edit the
 * JSON: fix the schema file, re-run `npm run build:elements-index` there,
 * and copy the file here. Fields a schema file does not state are empty;
 * the `gaps` array names them, and this page marks those sections.
 */

type TagFamily = "sem" | "npl";

interface TagAttr {
  name: string;
  required: boolean | null;
  type: string;
  allowedValues: string[];
  default: string | null;
  description: string;
}

interface TagChild {
  name: string;
  note: string;
}

interface TagRecord {
  name: string;
  family: TagFamily;
  source: string;
  summary: string;
  description: string;
  attributes: TagAttr[];
  children: TagChild[];
  example: string;
  optionsIn?: string;
}

interface ElementsIndex {
  $comment: string;
  specVersion: string;
  generatedFrom: string[];
  tagCount: number;
  tags: TagRecord[];
  gaps: Array<{ tag: string; missing: string[] }>;
}

const INDEX = elementsIndex as ElementsIndex;
const TAGS = INDEX.tags;
const GAP_MISSING = new Map(INDEX.gaps.map((g) => [g.tag, g.missing]));
const FAMILIES: Array<{ family: TagFamily; title: string; blurb: string }> = [
  {
    family: "sem",
    title: "SemText elements",
    blurb:
      "The sem-* XHTML vocabulary — the document-shaped format every SemText consumer reads.",
  },
  {
    family: "npl",
    title: "NPL elements",
    blurb:
      "The npl-* components — display renders of NPL prompt blocks (agent introspection, critique, reasoning).",
  },
];

const esc = (s: string) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function attrType(a: TagAttr): string {
  const parts: string[] = [];
  if (a.type) parts.push(a.type);
  if (a.allowedValues.length) parts.push(a.allowedValues.map((v) => `\`${v}\``).join(" | "));
  return parts.join(" · ");
}

function defaultText(a: TagAttr): string {
  if (a.default === null) return "—";
  if (a.default === "") return "(empty)";
  return a.default;
}

function requiredText(a: TagAttr): string {
  if (a.required === true) return "yes";
  if (a.required === false) return "no";
  return "—";
}

/*
 * One small vanilla script, the /elements/ pattern: the input narrows the
 * sidebar links and the tag sections by tag name or summary. With no JS
 * nothing runs and the page shows every tag — the static render is whole.
 */
const FILTER_SCRIPT = `(function(){
  function ready(fn){ if(document.readyState!=="loading"){fn();}else{document.addEventListener("DOMContentLoaded",fn);} }
  ready(function(){
    var input=document.getElementById("ref-search");
    if(!input){return;}
    var sections=document.querySelectorAll("[data-ref-tag]");
    function linkTarget(a){
      var el=document.getElementById(a.getAttribute("href").slice(1));
      return el?el.getAttribute("data-ref"):"";
    }
    var links=[].slice.call(document.querySelectorAll('nav[aria-label="Docs"] a[href^="#"]'));
    var count=document.getElementById("ref-count");
    function apply(){
      var q=input.value.trim().toLowerCase();
      var shown=0;
      for(var i=0;i<sections.length;i++){
        var el=sections[i];
        el.hidden=q.length>0&&el.getAttribute("data-ref").indexOf(q)===-1;
        if(!el.hidden){shown++;}
      }
      for(var j=0;j<links.length;j++){
        var a=links[j];
        a.hidden=q.length>0&&linkTarget(a).indexOf(q)===-1;
      }
      if(count){count.textContent=q.length>0?shown+" of "+sections.length+" tags":"";
        count.hidden=q.length===0;}
    }
    input.addEventListener("input",apply);
  });
})();`;

export default function ReferencePage() {
  const semTags = TAGS.filter((t) => t.family === "sem");
  const nplTags = TAGS.filter((t) => t.family === "npl");

  const familyGroup = (title: string, tags: TagRecord[]) => ({
    title,
    items: tags.map((t) => ({
      key: `ref-${t.name}`,
      label: t.name,
      href: `#${t.name}`,
    })),
  });

  const groups = [
    { title: "Guides", items: [{ key: "cli", label: "CLI commands", href: "/docs/" }] },
    { title: "Reference", items: [
      { key: "elements", label: "Elements", href: "/elements/" },
      { key: "reference", label: "Tag reference", href: "/reference/" },
    ] },
    familyGroup("SemText elements", semTags),
    familyGroup("NPL elements", nplTags),
  ];

  return (
    <DocsShell active="reference" groups={groups}>
      <main id="main">
        <p className="g-eyebrow">Reference</p>
        <h1 className="mt-2 text-3xl font-semibold tracking-tight text-ink sm:text-4xl">
          Every tag, from the spec
        </h1>
        <p className="mt-4 max-w-3xl text-base leading-7 text-ink-mute">
          All {INDEX.tagCount} SemText and NPL tags with their options,
          children and an authored example — generated from the normative
          schema files of spec v{INDEX.specVersion}
          {" "}(<code className="font-mono">spec/schema/sem-*.md</code>,{" "}
          <code className="font-mono">spec/schema/npl/*.md</code>), so the page
          cannot drift from the spec. Fields a schema file does not state stay
          empty and the tag is marked below.
        </p>

        <div className="mt-8 max-w-3xl">
          <label htmlFor="ref-search" className="g-nav-title">
            Filter tags
          </label>
          <input
            id="ref-search"
            type="search"
            placeholder="Type a tag name or a summary word — e.g. quiz, chronology, agent"
            autoComplete="off"
            className="mt-2 w-full rounded-md border border-white/15 bg-white/5 px-3 py-2 font-mono text-sm text-ink placeholder:text-ink-faint focus:border-white/40 focus:outline-none"
          />
          <p id="ref-count" hidden className="mt-2 text-sm text-ink-mute" aria-live="polite" />
        </div>

        {FAMILIES.map(({ family, title, blurb }) => {
          const tags = TAGS.filter((t) => t.family === family);
          return (
            <section
              key={family}
              aria-labelledby={`family-${family}-h`}
              className="mt-14 scroll-mt-24"
            >
              <h2
                id={`family-${family}-h`}
                className="text-2xl font-semibold tracking-tight text-ink"
              >
                {title}
              </h2>
              <p className="mt-3 max-w-3xl leading-relaxed text-ink-mute">{blurb}</p>
              {tags.map((t) => (
                <TagSection key={t.name} tag={t} />
              ))}
            </section>
          );
        })}

        <script defer src="/semtext/semtext-fallback.js" />
        <script defer dangerouslySetInnerHTML={{ __html: FILTER_SCRIPT }} />
      </main>
    </DocsShell>
  );
}

function TagSection({ tag }: { tag: TagRecord }) {
  const missing = GAP_MISSING.get(tag.name) ?? [];
  const gapNote = missing.includes("summary") || missing.includes("description");
  const search = `${tag.name} ${tag.summary}`.toLowerCase();

  return (
    <article
      id={tag.name}
      data-ref-tag={tag.name}
      data-ref={search}
      aria-labelledby={`${tag.name}-h`}
      className="mt-10 scroll-mt-24 border-t border-white/10 pt-8"
    >
      <h3 id={`${tag.name}-h`} className="text-xl font-semibold tracking-tight text-ink">
        <code className="font-mono">&lt;{tag.name}&gt;</code>
        <span className="ml-3 align-middle font-sans text-xs font-normal uppercase tracking-wide text-ink-faint">
          {tag.family === "sem" ? "SemText" : "NPL"}
        </span>
      </h3>

      {tag.summary ? (
        <p className="mt-3 max-w-3xl text-base leading-7 text-ink">{tag.summary}</p>
      ) : gapNote ? (
        <p className="mt-3 max-w-3xl text-sm italic leading-6 text-ink-faint">
          The schema file does not state a summary for this tag
          {missing.length ? ` (missing: ${missing.join(", ")})` : ""} — see the
          normative schema for the contract.
        </p>
      ) : null}

      {tag.description && tag.description !== tag.summary ? (
        <p className="mt-2 max-w-3xl text-sm leading-6 text-ink-mute">{tag.description}</p>
      ) : null}

      {tag.optionsIn ? (
        <p className="mt-3 max-w-3xl text-sm leading-6 text-ink-mute">
          Shares its schema with{" "}
          <a href={`#${tag.optionsIn}`} className="underline decoration-white/30 underline-offset-2 hover:decoration-white/70">
            <code className="font-mono">&lt;{tag.optionsIn}&gt;</code>
          </a>{" "}
          — the option bullets below belong to that element&apos;s contract.
        </p>
      ) : null}

      {tag.attributes.length > 0 ? (
        <div className="mt-5 max-w-3xl overflow-x-auto">
          <table className="w-full border-collapse text-left text-sm">
            <thead>
              <tr className="border-b border-white/15 text-xs uppercase tracking-wide text-ink-faint">
                <th scope="col" className="py-2 pr-4 font-medium">Option</th>
                <th scope="col" className="py-2 pr-4 font-medium">Required</th>
                <th scope="col" className="py-2 pr-4 font-medium">Type · values</th>
                <th scope="col" className="py-2 pr-4 font-medium">Default</th>
                <th scope="col" className="py-2 font-medium">Description</th>
              </tr>
            </thead>
            <tbody>
              {tag.attributes.map((a) => (
                <tr key={a.name} className="border-b border-white/5 align-top">
                  <td className="py-2 pr-4 font-mono text-ink">{a.name}</td>
                  <td className="py-2 pr-4 text-ink-mute">{requiredText(a)}</td>
                  <td className="py-2 pr-4 font-mono text-ink-mute">
                    {attrType(a) || "—"}
                  </td>
                  <td className="py-2 pr-4 font-mono text-ink-mute">{defaultText(a)}</td>
                  <td className="py-2 leading-6 text-ink-mute">{a.description || "—"}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      ) : (
        <p className="mt-5 max-w-3xl text-sm leading-6 text-ink-mute">
          {tag.attributes.length === 0 && missing.includes("attributes")
            ? "The schema file states no options for this tag."
            : "No options beyond the global attribute catalog are stated for this tag."}
        </p>
      )}

      {tag.children.length > 0 ? (
        <div className="mt-5 max-w-3xl">
          <p className="g-nav-title">Children</p>
          <ul className="mt-2 flex flex-col gap-1 text-sm leading-6 text-ink-mute" role="list">
            {tag.children.map((c) => (
              <li key={c.name}>
                <code className="font-mono text-ink">&lt;{c.name}&gt;</code>
                {c.note ? <span className="ml-2">{c.note}</span> : null}
              </li>
            ))}
          </ul>
        </div>
      ) : null}

      {tag.example ? (
        tag.name === "sem-md" ? (
          /* The one example that IS Markdown: a Render/Source toggle over
             the same authored block, like the landing's view control.
             Render (the default) renders the table — statically for the
             zero-JS export, live via the chunks/sem-md.js upgrade once
             the lazy loader hydrates this example. */
          <div className="mt-5 max-w-3xl">
            <SemMdExample
              source={tag.example}
              renderedHtml={REFERENCE_SEM_MD_RENDERED}
              chromeLabel="sem-md — the authored block, rendered"
            />
          </div>
        ) : (
          <figure
            className="code-window mt-5 max-w-3xl"
            aria-label={`Authored ${tag.name} example`}
          >
            <div className="code-chrome">
              <span className="dot live" aria-hidden="true" />
              <span className="font-mono">sem-code — authoring form</span>
            </div>
            <sem-code lang="html" filename={`${tag.name}.html`}>
              <pre>
                <code>{esc(tag.example)}</code>
              </pre>
            </sem-code>
          </figure>
        )
      ) : (
        <p className="mt-5 max-w-3xl text-sm italic leading-6 text-ink-faint">
          The schema file states no authoring example for this tag.
        </p>
      )}

      <p className="mt-4 text-xs text-ink-faint">
        Source:{" "}
        <code className="font-mono">{tag.source}</code>
      </p>
    </article>
  );
}
