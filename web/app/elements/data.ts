/** Search text per entry: name + purpose + kind + attribute text, lowercased. */
export function searchIndex(e: GlossaryEntry): string {
  return [
    e.name,
    e.purpose,
    e.kind,
    ...e.attributes.map((a) => `${a.name} ${a.values}`),
    e.note ?? "",
    e.liveNote ?? "",
  ]
    .join(" ")
    .toLowerCase();
}
