/*
 * SemText element glossary — reviewable data file.
 *
 * Source of truth: the tag catalog in
 * noizu-labs-ml/npl-enhanced-content `spec/semtext.sem.html` §5 (Tag catalog)
 * and the machine contract `spec/schema/semtext.schema.json` ($defs —
 * attribute names, allowed values, required flags). Extraction record list:
 * `spec/extraction.md` §3 rule 1 (the 21 minting element types).
 *
 * `kind`:
 *   - "Lit"    — the element is defined as a custom element and upgraded by
 *                the Lit bundle (spec §4 rule 2).
 *   - "native" — no custom element; vocabulary CSS renders it, the fallback
 *                bundle adds behaviour where the spec gives it a handler.
 *   - "chrome" — reading chrome; mints nothing (spec §5, sem-reader).
 *
 * `validated: false` marks elements the spec documents but the validator's
 * schema does not know yet (sem-embed renderer not implemented; sem-question
 * / sem-option are Tier-1 demo elements) — their examples are excluded from
 * the semtext-validate run.
 */

export type ElementKind = "Lit" | "native" | "chrome";

export interface ElementAttr {
  name: string;
  values: string;
  required?: boolean;
}

export interface GlossaryEntry {
  id: string;
  name: string;
  purpose: string;
  kind: ElementKind;
  /** Mints an extraction record (extraction.md §3 rule 1). */
  mints: boolean;
  attributes: ElementAttr[];
  /** XHTML example — rendered live and shown as source. */
  example: string;
  /** Caveat about what the live render on this page can show. */
  liveNote?: string;
  /** Extra prose shown under the purpose. */
  note?: string;
  /** Normative reference. */
  spec: string;
  /** false = not in the validator schema yet (see header). */
  validated?: boolean;
}

