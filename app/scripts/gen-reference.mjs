#!/usr/bin/env node
/*
 * gen-reference.mjs — P0 refresh path for the reference data (design v2 §2.3).
 *
 * Sources of truth (read-only):
 *   <web>/data/elements.json                  — generated from spec/schema/*.md
 *   <web>/data/bundles.json                   — generated from public/semtext/*
 *   <web>/data/reference-example-variants.ts  — hand-authored variants
 *   <web>/data/reference-glossary.ts          — hand-authored 8-tag supplement
 *
 * Outputs (written into this repo):
 *   app/backend/priv/data/elements.json           (byte copy)
 *   app/backend/priv/data/bundles.json            (byte copy)
 *   app/backend/priv/data/example-variants.json   (TS default export -> JSON)
 *   app/backend/lib/semtext/reference/glossary.ex (generated module)
 *   app/backend/lib/semtext/reference/buckets.ex  (generated module)
 *
 * Usage:  node app/scripts/gen-reference.mjs --web <path-to-landing-preview/web>
 *
 * The Elixir side (`Semtext.Reference.*`) compile-time-loads these outputs;
 * a `mix semtext.gen_reference` task shells this script. After a re-sync the
 * reference pages pick the new data up on the next compile (the modules use
 * @external_resource, so editing the JSON recompiles them).
 *
 * reference-buckets.ts imports via the "@/" alias, which bare Node cannot
 * resolve, so the whole data dir is copied to a temp dir with alias imports
 * rewritten to relative paths before the import. The emitted buckets.ex
 * keeps the TS bucket text verbatim (labels/descriptions/names) and re-runs
 * the coverage validation at compile time.
 */
import { readFileSync, writeFileSync, mkdirSync, mkdtempSync, cpSync, readdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);
const webFlag = args.indexOf("--web");
if (webFlag === -1 || !args[webFlag + 1]) {
  console.error("usage: node gen-reference.mjs --web <path-to-landing-preview/web>");
  process.exit(3);
}
const web = resolve(args[webFlag + 1]);
const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const backend = join(repoRoot, "app", "backend");
const privData = join(backend, "priv", "data");
const glossaryEx = join(backend, "lib", "semtext", "reference", "glossary.ex");

// ————— JSON copies (byte-for-byte) —————

mkdirSync(privData, { recursive: true });
writeFileSync(join(privData, "elements.json"), readFileSync(join(web, "data", "elements.json")));
writeFileSync(join(privData, "bundles.json"), readFileSync(join(web, "data", "bundles.json")));

// ————— variants TS -> JSON —————
// Node's native type stripping imports the TS module directly; the file's
// only non-JS syntax is the interface + the type annotation, both erasable.
const { EXAMPLE_VARIANTS } = await import(`file://${join(web, "data", "reference-example-variants.ts")}`);
writeFileSync(
  join(privData, "example-variants.json"),
  JSON.stringify(EXAMPLE_VARIANTS, null, 2) + "\n",
);

// ————— glossary TS -> Elixir module —————

const { GLOSSARY_TAGS } = await import(`file://${join(web, "data", "reference-glossary.ts")}`);

const elixirString = (s) => JSON.stringify(s); // JSON string escaping is Elixir-compatible

const attrLines = (attrs) =>
  attrs.length
    ? "      attributes: [\n" +
      attrs
        .map((a) => `        Norm.attr(${elixirString(a.name)}, ${elixirString(a.type)})`)
        .join(",\n") +
      "\n      ],\n"
    : "";

const tagBlock = (t) =>
  "    Norm.tag(" +
  elixirString(t.name) +
  ", " +
  elixirString(t.source) +
  ",\n" +
  `      summary: ${elixirString(t.summary)},\n` +
  `      description: ${elixirString(t.description)},\n` +
  attrLines(t.attributes) +
  `      example: ~S"""\n${t.example}\n      """\n    )`;

const module_source = `defmodule Semtext.Reference.Glossary do
  @moduledoc """
  Hand-authored supplement to \`Semtext.Reference.Elements\`.

  \`priv/data/elements.json\` is generated by upstream tooling — never edit it
  by hand. These elements are documented in the spec (root conventions and
  the sem-facts family) but have no schema file of their own, so the
  generator cannot emit them. Their content moved verbatim from the retired
  /elements/ glossary page, itself sourced from the spec's section 5 tag
  catalog and spec/schema/semtext.schema.json. Options listed here are
  exactly the ones the glossary stated — nothing invented.

  THIS FILE IS GENERATED by \`mix semtext.gen_reference\` from the landing
  preview's \`web/data/reference-glossary.ts\` — edit the TS source, then
  regenerate. Committed so the release embeds it without a TS toolchain.
  """

  # ————— constructors (the TS source's attr() helper) —————
  # A module-body attribute cannot call the enclosing module's own
  # functions, so the constructors live in a nested Norm module —
  # cross-module calls compile (and run at compile time, embedding the
  # result).

  defmodule Norm do
    @moduledoc false

    def tag(name, source, opts) do
      %{
        name: name,
        family: :sem,
        source: source,
        summary: Keyword.fetch!(opts, :summary),
        description: Keyword.fetch!(opts, :description),
        attributes: Keyword.get(opts, :attributes, []),
        children: [],
        example: Keyword.fetch!(opts, :example),
        options_in: nil
      }
    end

    def attr(name, type) do
      %{
        name: name,
        required: nil,
        type: type,
        allowed_values: [],
        default: nil,
        description: ""
      }
    end
  end

  @tags [
${GLOSSARY_TAGS.map(tagBlock).join(",\n")}
  ]

  @doc "The hand-authored elements, same order as the TS source."
  @spec all() :: [map()]
  def all, do: @tags

  @doc "The glossary element record by tag name, or nil."
  @spec get(String.t()) :: map() | nil
  def get(name), do: Enum.find(@tags, &(&1.name == name))
end
`;

mkdirSync(dirname(glossaryEx), { recursive: true });
writeFileSync(glossaryEx, module_source);

// ————— buckets TS -> Elixir module —————
// reference-buckets.ts imports via the "@/" alias; bare Node cannot resolve
// it, so copy the data dir to a temp dir and rewrite alias imports to
// relative paths before importing. The exported REFERENCE_BUCKETS arrive
// already resolved (tags attached), so the emission is a straight dump.

const tmpData = mkdtempSync(join(tmpdir(), "genref-"));
cpSync(join(web, "data"), join(tmpData, "data"), { recursive: true });

for (const f of readdirSync(join(tmpData, "data"))) {
  if (f.endsWith(".ts")) {
    const p = join(tmpData, "data", f);
    writeFileSync(p, readFileSync(p, "utf8")
      .replace(/"@\/data\/([A-Za-z0-9_-]+)"/g, (_m, mod) => `"./${mod}.ts"`)
      .replace(/"@\/data\/([A-Za-z0-9_-]+\.[a-z]+)"/g, (_m, mod) => `"./${mod}"`)
      .replace(/from "(\.\/[A-Za-z0-9_-]+\.json)"/g, (_m, mod) => `from "${mod}" with { type: "json" }`));
  }
}

const { REFERENCE_BUCKETS } = await import(`file://${join(tmpData, "data", "reference-buckets.ts")}`);

const bucketBlock = (b) =>
  `      Norm.bucket_def(${elixirString(b.id)}, ${elixirString(b.label)},\n` +
  `        description: ${elixirString(b.description)},\n` +
  `        names: [\n` +
  b.tags.map((t) => `          ${elixirString(t.name)}`).join(",\n") +
  `\n        ]\n      )`;

const bucketsEx = join(backend, "lib", "semtext", "reference", "buckets.ex");

const buckets_source = `defmodule Semtext.Reference.Buckets do
  @moduledoc """
  Editorial grouping of the SemText element reference (mechanical port of
  \`web/data/reference-buckets.ts\`): every bucket is one job a reader hires
  the elements for, and every SemText tag appears in exactly one bucket.
  Coverage is validated — \`validate!/0\` raises when a tag is unknown,
  duplicated across buckets, or left without a bucket — and the ExUnit suite
  pins it (a spec tag without a bucket fails \`mix test\`), replacing the TS
  module's import-time check.

  NPL tags are not bucketed: they are one display family and keep their own
  single group. Consumers (the reference index, tag pages, the docs sidebar)
  render \`buckets/0\` in order; \`bucket_of/1\` answers "which bucket is this
  tag in".

  THIS FILE IS GENERATED by \`mix semtext.gen_reference\` from the landing
  preview's \`web/data/reference-buckets.ts\` — bucket labels, descriptions
  and name lists are the TS source verbatim; edit the TS, then regenerate.
  """

  alias Semtext.Reference.Tags

  @typedoc "One bucket: stable id, display label, description, ordered tags."
  @type bucket :: %{
          id: String.t(),
          label: String.t(),
          description: String.t(),
          tags: [Tags.tag()]
        }

  # ————— compile-time resolution + validation —————
  # Nested helper module: module-body attributes cannot call the enclosing
  # module's own functions; cross-module calls compile (and run at compile
  # time, embedding the result).

  defmodule Norm do
    @moduledoc false

    def bucket_def(id, label, opts) do
      %{
        id: id,
        label: label,
        description: Keyword.fetch!(opts, :description),
        names: Keyword.fetch!(opts, :names)
      }
    end

    def bucket_defs do
      [
${REFERENCE_BUCKETS.map(bucketBlock).join(",\n")}
      ]
    end

    def resolve do
      by_name = Map.new(Tags.sem_tags(), fn t -> {t.name, t} end)
      all_names = Enum.flat_map(bucket_defs(), & &1.names)

      Enum.each(all_names, fn name ->
        unless Map.has_key?(by_name, name) do
          raise ArgumentError,
            "reference-buckets: \\"\#{name}\\" is not a SemText tag in the inventory — rename or drop it"
        end
      end)

      dupes = all_names -- Enum.uniq(all_names)

      if dupes != [] do
        raise ArgumentError,
          "reference-buckets: \#{Enum.map_join(Enum.uniq(dupes), ", ", &"\\"\#{&1}\\"")} assigned to two buckets"
      end

      buckets =
        Enum.map(bucket_defs(), fn b ->
          %{
            id: b.id,
            label: b.label,
            description: b.description,
            tags: Enum.map(b.names, &Map.fetch!(by_name, &1))
          }
        end)

      covered = MapSet.new(all_names)
      uncovered = Tags.sem_tags() |> Enum.reject(&MapSet.member?(covered, &1.name))

      if uncovered != [] do
        raise ArgumentError,
          "reference-buckets: SemText tags with no bucket: \#{Enum.map_join(uncovered, ", ", & &1.name)}"
      end

      buckets
    end
  end

  @buckets Norm.resolve()

  @doc "The SemText reference, grouped for a reader, in display order."
  @spec buckets() :: [bucket()]
  def buckets, do: @buckets

  @doc "The bucket a SemText tag belongs to (nil for NPL tags — they are not bucketed)."
  @spec bucket_of(String.t()) :: bucket() | nil
  def bucket_of(name) do
    Enum.find(@buckets, fn b -> Enum.any?(b.tags, &(&1.name == name)) end)
  end

  @doc """
  Coverage validation: raises when a bucket names an unknown tag, a tag is
  assigned to two buckets, or a SemText tag has no bucket. The Next site ran
  this at import time; here it runs at compile time AND in the test suite.
  """
  @spec validate!() :: :ok
  def validate! do
    Norm.resolve()
    :ok
  end
end
`;

writeFileSync(bucketsEx, buckets_source);

console.log(
  `gen-reference: elements.json+bundles.json copied, ` +
    `${Object.keys(EXAMPLE_VARIANTS).length} variant tags (${Object.values(EXAMPLE_VARIANTS).reduce((a, v) => a + v.length, 0)} entries), ` +
    `${GLOSSARY_TAGS.length} glossary tags, ${REFERENCE_BUCKETS.length} buckets -> ${bucketsEx}`,
);
