#!/usr/bin/env node
/*
 * gen-search-tags.mjs — regenerate the INTERIM docs/search data
 * (app/backend/priv/data/docs/search-tags.json) from the same sources of
 * truth the compile-time reference modules use:
 *
 *   <web>/data/elements.json                       — generated inventory
 *   <web>/data/reference-glossary.ts               — hand-authored supplement
 *   <web>/data/reference-buckets.ts                — editorial buckets (id/label/description/names)
 *   app/backend/priv/data/description-overrides.json — plain-language copy layer
 *
 * The overrides are applied HERE (same rule as Semtext.Reference.Tags):
 * a tag without an override entry fails the run — new elements must ship
 * plain-language copy, not stale generated prose.
 *
 * Usage:  node app/scripts/gen-search-tags.mjs --web <path-to-web-dir>
 *
 * Long-term this file retires once SearchIndex reads the compile-time
 * Semtext.Reference.* modules directly (see its moduledoc); until then
 * re-run this after every gen-reference refresh.
 */
import { readFileSync, writeFileSync, mkdirSync, mkdtempSync, cpSync, readdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);
const webFlag = args.indexOf("--web");
if (webFlag === -1 || !args[webFlag + 1]) {
  console.error("usage: node gen-search-tags.mjs --web <path-to-web-dir>");
  process.exit(3);
}
const web = resolve(args[webFlag + 1]);
const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const backend = join(repoRoot, "app", "backend");

const elements = JSON.parse(readFileSync(join(web, "data", "elements.json"), "utf8"));
const overridesPath = join(backend, "priv", "data", "description-overrides.json");
const overrides = JSON.parse(readFileSync(overridesPath, "utf8")).overrides;

// Overrides are mandatory copy: every tag needs [summary, description].
const applyOverride = (t) => {
  const o = overrides[t.name];
  if (!o) throw new Error(`description-overrides.json has no entry for tag ${t.name}`);
  const [summary, description] = o;
  return {
    name: t.name,
    family: t.family,
    summary,
    description,
    attributes: (t.attributes || []).map((a) => ({ name: a.name, description: a.description || "" })),
    children: (t.children || []).map((c) => c.name ?? c),
  };
};

const { GLOSSARY_TAGS } = await import(`file://${join(web, "data", "reference-glossary.ts")}`);

// reference-buckets.ts imports via the "@/" alias; bare Node cannot resolve
// it — same temp-dir rewrite as gen-reference.mjs.
const tmpData = mkdtempSync(join(tmpdir(), "gensearch-"));
cpSync(join(web, "data"), join(tmpData, "data"), { recursive: true });
for (const f of readdirSync(join(tmpData, "data"))) {
  if (f.endsWith(".ts")) {
    const p = join(tmpData, "data", f);
    writeFileSync(
      p,
      readFileSync(p, "utf8")
        .replace(/"@\/data\/([A-Za-z0-9_-]+)"/g, (_m, mod) => `"./${mod}.ts"`)
        .replace(/"@\/data\/([A-Za-z0-9_-]+\.[a-z]+)"/g, (_m, mod) => `"./${mod}"`)
        .replace(/from "(\.\/[A-Za-z0-9_-]+\.json)"/g, (_m, mod) => `from "${mod}" with { type: "json" }`),
    );
  }
}
const { REFERENCE_BUCKETS } = await import(`file://${join(tmpData, "data", "reference-buckets.ts")}`);

const tags = [...elements.tags, ...GLOSSARY_TAGS].map(applyOverride);
const seen = new Set();
for (const t of tags) {
  if (seen.has(t.name)) throw new Error(`duplicate tag in search data: ${t.name}`);
  seen.add(t.name);
}

const out = {
  $comment:
    "INTERIM nav/search data behind SemtextWeb.Docs.SearchIndex. Regenerated by app/scripts/gen-search-tags.mjs from web/data/{elements.json,reference-glossary.ts,reference-buckets.ts} + priv/data/description-overrides.json (overrides applied). Long-term source: the compile-time Semtext.Reference.* modules — converge on those and retire this file.",
  specVersion: elements.specVersion,
  tags,
  buckets: REFERENCE_BUCKETS.map((b) => ({
    id: b.id,
    label: b.label,
    description: b.description,
    tags: b.tags.map((t) => t.name),
  })),
};

const outFile = join(backend, "priv", "data", "docs", "search-tags.json");
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, JSON.stringify(out, null, 1) + "\n");
console.log(
  `gen-search-tags: ${tags.length} tags (${new Set(tags.map((t) => t.family)).size} families), ${out.buckets.length} buckets -> ${outFile}`,
);
