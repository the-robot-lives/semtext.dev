defmodule Semtext.Reference.Buckets do
  @moduledoc """
  Editorial grouping of the SemText element reference (mechanical port of
  `web/data/reference-buckets.ts`): every bucket is one job a reader hires
  the elements for, and every SemText tag appears in exactly one bucket.
  Coverage is validated — `validate!/0` raises when a tag is unknown,
  duplicated across buckets, or left without a bucket — and the ExUnit suite
  pins it (a spec tag without a bucket fails `mix test`), replacing the TS
  module's import-time check.

  NPL tags are not bucketed: they are one display family and keep their own
  single group. Consumers (the reference index, tag pages, the docs sidebar)
  render `buckets/0` in order; `bucket_of/1` answers "which bucket is this
  tag in".

  THIS FILE IS GENERATED by `mix semtext.gen_reference` from the landing
  preview's `web/data/reference-buckets.ts` — bucket labels, descriptions
  and name lists are the TS source verbatim; edit the TS, then regenerate.
  """

  alias Semtext.Reference.Tags

  @typedoc "One bucket: stable id, display label, description, ordered tags."
  @type bucket :: %{
          id: String.t(),
          label: String.t(),
          description: String.t(),
          tags: [Tags.tag()]
        }

  # ————— compile-time resolution + validation —————
  # Nested helper module: module-body attributes cannot call the enclosing
  # module's own functions; cross-module calls compile (and run at compile
  # time, embedding the result).

  defmodule Norm do
    @moduledoc false

    def bucket_def(id, label, opts) do
      %{
        id: id,
        label: label,
        description: Keyword.fetch!(opts, :description),
        names: Keyword.fetch!(opts, :names)
      }
    end

    def bucket_defs do
      [
      Norm.bucket_def("document", "Document & structure",
        description: "The root wrapper, reading chrome, audience declarations and document-level metadata that frame a SemText document.",
        names: [
          "sem-enhanced-document",
          "sem-reader",
          "sem-audiences",
          "sem-profile",
          "agent"
        ]
      ),
      Norm.bucket_def("prose", "Prose & code",
        description: "Content blocks beyond plain HTML — Markdown bodies, callouts and source listings with provenance.",
        names: [
          "sem-md",
          "sem-note",
          "sem-code",
          "sem-browser"
        ]
      ),
      Norm.bucket_def("disclosure", "Disclosure & views",
        description: "The same content under different reading interactions — occluded detail, Q→A reveal, markup flip, perspective tabs.",
        names: [
          "sem-details",
          "sem-detail",
          "highlight",
          "sem-reveal",
          "sem-source",
          "sem-views",
          "sem-view"
        ]
      ),
      Norm.bucket_def("recall", "Facts & recall",
        description: "Assertable statement/conclusion pairs — the citable unit — with the quiz candidates and distractors built on them.",
        names: [
          "sem-facts",
          "sem-fact",
          "statement",
          "conclusion",
          "incorrect-statement",
          "sem-question",
          "sem-option"
        ]
      ),
      Norm.bucket_def("data", "Data & tables",
        description: "Authored tables and the data-visualizer's named buckets, joins and editable queries.",
        names: [
          "sem-table",
          "sem-data-visualizer",
          "sem-data-source",
          "sem-data-join",
          "sem-data-query"
        ]
      ),
      Norm.bucket_def("sequence", "Sequences & progress",
        description: "Ordered, status-annotated content — timelines, procedures and completion meters.",
        names: [
          "sem-chronology",
          "sem-event",
          "sem-procedure",
          "sem-step",
          "sem-progress"
        ]
      ),
      Norm.bucket_def("definitions", "Definitions & citations",
        description: "Closed key/value assertions and the numbered works the prose cites.",
        names: [
          "sem-properties",
          "sem-property",
          "sem-references",
          "sem-reference"
        ]
      )
      ]
    end

    def resolve do
      by_name = Map.new(Tags.sem_tags(), fn t -> {t.name, t} end)
      all_names = Enum.flat_map(bucket_defs(), & &1.names)

      Enum.each(all_names, fn name ->
        unless Map.has_key?(by_name, name) do
          raise ArgumentError,
            "reference-buckets: \"#{name}\" is not a SemText tag in the inventory — rename or drop it"
        end
      end)

      dupes = all_names -- Enum.uniq(all_names)

      if dupes != [] do
        raise ArgumentError,
          "reference-buckets: #{Enum.map_join(Enum.uniq(dupes), ", ", &"\"#{&1}\"")} assigned to two buckets"
      end

      buckets =
        Enum.map(bucket_defs(), fn b ->
          %{
            id: b.id,
            label: b.label,
            description: b.description,
            tags: Enum.map(b.names, &Map.fetch!(by_name, &1))
          }
        end)

      covered = MapSet.new(all_names)
      uncovered = Tags.sem_tags() |> Enum.reject(&MapSet.member?(covered, &1.name))

      if uncovered != [] do
        raise ArgumentError,
          "reference-buckets: SemText tags with no bucket: #{Enum.map_join(uncovered, ", ", & &1.name)}"
      end

      buckets
    end
  end

  @buckets Norm.resolve()

  @doc "The SemText reference, grouped for a reader, in display order."
  @spec buckets() :: [bucket()]
  def buckets, do: @buckets

  @doc "The bucket a SemText tag belongs to (nil for NPL tags — they are not bucketed)."
  @spec bucket_of(String.t()) :: bucket() | nil
  def bucket_of(name) do
    Enum.find(@buckets, fn b -> Enum.any?(b.tags, &(&1.name == name)) end)
  end

  @doc """
  Coverage validation: raises when a bucket names an unknown tag, a tag is
  assigned to two buckets, or a SemText tag has no bucket. The Next site ran
  this at import time; here it runs at compile time AND in the test suite.
  """
  @spec validate!() :: :ok
  def validate! do
    Norm.resolve()
    :ok
  end
end
