defmodule Semtext.Reference.Elements do
  @moduledoc """
  Generated element inventory, compile-time-loaded from `priv/data/elements.json`.

  The JSON is generated by `scripts/build-elements-index.mjs` in
  noizu-labs-ml/npl-enhanced-content from `spec/schema/*.md` — never hand-edit
  it. `mix semtext.gen_reference` (this repo) refreshes the copy. Design v2
  §2.3 / R3: reference data is a build artifact embedded in the release, not a
  runtime dependency.

  Tag records are plain atom-keyed maps:

      %{
        name: "sem-note", family: :sem, source: "spec/schema/sem-note.md",
        summary: "...", description: "...",
        attributes: [%{name: "variant", required: false, type: "string",
                       allowed_values: [], default: nil, description: "..."}],
        children: [%{name: "sem-md", note: ""}],
        example: "<sem-note ...>...</sem-note>", options_in: nil
      }
  """

  # ————— compile-time normalization —————
  # Nested helper module: module-body attributes cannot call the enclosing
  # module's own functions, but cross-module calls compile fine (and run at
  # compile time, embedding the result).

  defmodule Norm do
    @moduledoc false

    def normalize_tag(t) do
      %{
        name: t["name"],
        family: family(t["family"]),
        source: t["source"],
        summary: t["summary"] || "",
        description: t["description"] || "",
        attributes: Enum.map(t["attributes"] || [], &normalize_attr/1),
        children:
          Enum.map(t["children"] || [], fn c ->
            %{name: c["name"], note: c["note"] || ""}
          end),
        example: t["example"] || "",
        options_in: t["optionsIn"]
      }
    end

    defp family("sem"), do: :sem
  defp family("npl"), do: :npl

  defp family(other), do: raise("unknown element family in elements.json: #{inspect(other)}")

  def normalize_attr(a) do
      %{
        name: a["name"],
        required: a["required"],
        type: a["type"] || "",
        allowed_values: a["allowedValues"] || [],
        default: a["default"],
        description: a["description"] || ""
      }
    end
  end

  @external_resource path = Path.expand("../../../priv/data/elements.json", __DIR__)
  {:ok, decoded} = path |> File.read!() |> Jason.decode()

  @tags Enum.map(decoded["tags"], &Norm.normalize_tag/1)
  @by_name Map.new(@tags, fn t -> {t.name, t} end)
  @gaps Map.new(decoded["gaps"] || [], fn g -> {g["tag"], g["missing"]} end)
  @spec_version decoded["specVersion"]
  @declared_count decoded["tagCount"]

  @doc "Spec version the generated half was built from (e.g. \"0.6\")."
  @spec spec_version() :: String.t()
  def spec_version, do: @spec_version

  @doc "Every generated element (the hand-authored supplement lives in Glossary)."
  @spec all() :: [map()]
  def all, do: @tags

  @doc "The element record by tag name, or nil."
  @spec get(String.t()) :: map() | nil
  def get(name) when is_binary(name), do: Map.get(@by_name, name)

  @doc "Generated tag count as declared by the JSON (`tagCount`)."
  def declared_count, do: @declared_count

  @doc "Schema fields the generator could not find, per tag (map tag => missing list)."
  @spec gaps() :: %{optional(String.t()) => [String.t()]}
  def gaps, do: @gaps

  @doc "The missing-field list for one tag (empty list when none)."
  @spec missing_for(String.t()) :: [String.t()]
  def missing_for(name), do: Map.get(@gaps, name, [])
end
