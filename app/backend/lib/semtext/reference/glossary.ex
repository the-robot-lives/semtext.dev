defmodule Semtext.Reference.Glossary do
  @moduledoc """
  Hand-authored supplement to `Semtext.Reference.Elements`.

  `priv/data/elements.json` is generated by upstream tooling — never edit it
  by hand. These elements are documented in the spec (root conventions and
  the sem-facts family) but have no schema file of their own, so the
  generator cannot emit them. Their content moved verbatim from the retired
  /elements/ glossary page, itself sourced from the spec's section 5 tag
  catalog and spec/schema/semtext.schema.json. Options listed here are
  exactly the ones the glossary stated — nothing invented.

  THIS FILE IS GENERATED by `mix semtext.gen_reference` from the landing
  preview's `web/data/reference-glossary.ts` — edit the TS source, then
  regenerate. Committed so the release embeds it without a TS toolchain.
  """

  # ————— constructors (the TS source's attr() helper) —————
  # A module-body attribute cannot call the enclosing module's own
  # functions, so the constructors live in a nested Norm module —
  # cross-module calls compile (and run at compile time, embedding the
  # result).

  defmodule Norm do
    @moduledoc false

    def tag(name, source, opts) do
      %{
        name: name,
        family: :sem,
        source: source,
        summary: Keyword.fetch!(opts, :summary),
        description: Keyword.fetch!(opts, :description),
        attributes: Keyword.get(opts, :attributes, []),
        children: [],
        example: Keyword.fetch!(opts, :example),
        options_in: nil
      }
    end

    def attr(name, type) do
      %{
        name: name,
        required: nil,
        type: type,
        allowed_values: [],
        default: nil,
        description: ""
      }
    end
  end

  @tags [
    Norm.tag("sem-enhanced-document", "spec/conventions.md",
