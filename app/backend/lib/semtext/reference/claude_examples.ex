defmodule Semtext.Reference.ClaudeExamples do
  @moduledoc """
  The per-tag "SemText — Claude example" (compile-time load of
  `priv/data/claude-examples.json`): a complete, minimal, valid SemText
  fragment showing how Claude authors the tag inside a document, written in
  the sem-text-author conventions (markdown-content tables, `<sem-md>`,
  flat `<sem-code>`, `<highlight>` over `<b>`/`<strong>`, `cite` on
  references, no role attributes on procedures). Tags that only live inside
  a container ship WITH the container (`sem-reference` inside
  `sem-references`, `sem-step` inside `sem-procedure`); tags that only live
  under the root (`sem-reader`, `agent`) ship with the root.

  JSON shape — `"examples"` maps tag name to a record:

      "sem-tldr": {"source": "hand", "code": ["<sem-tldr id=\\"t\\">", "...", "</sem-tldr>"]}

  `code` is an array of lines (a plain string is accepted too). `source` is
  `"hand"` (hand-polished — the seeder never touches it) or `"seed"`
  (generated by `mix semtext.gen_reference --seed-claude-examples` from the
  tag's spec example, normalised; re-seeded on every run). Promote a seed to
  hand by editing it and flipping `source`.

  Mandatory per tag: `Semtext.Reference.Tags` fails the build when a tag has
  no entry or the file names an unknown tag, exactly like
  `description-overrides.json` — a card never ships without its example.
  Every example must pass `node bin/semtext-validate.mjs` (wrapped in a
  minimal `<sem-enhanced-document>`); `test/semtext/reference/claude_examples_test.exs`
  enforces it.
  """

  @path Path.expand("../../../priv/data/claude-examples.json", __DIR__)
  @external_resource @path

  @examples (case File.exists?(@path) do
               true ->
                 @path
                 |> File.read!()
                 |> Jason.decode!()
                 |> Map.fetch!("examples")
                 |> Map.new(fn {name, rec} ->
                   code =
                     case rec["code"] do
                       lines when is_list(lines) -> Enum.join(lines, "\n")
                       bin when is_binary(bin) -> bin
                     end

                   source =
                     case rec["source"] do
                       "hand" ->
                         :hand

                       "seed" ->
                         :seed

                       other ->
                         raise ArgumentError,
                               "claude-examples.json: bad source #{inspect(other)} for #{name}"
                     end

                   {name, %{code: String.trim(code), source: source}}
                 end)

               false ->
                 %{}
             end)

  @doc "Path of the source-of-truth JSON (used by the seeder and tests)."
  @spec path() :: String.t()
  def path, do: @path

  @doc "Every example record, keyed by tag name."
  @spec all() :: %{optional(String.t()) => %{code: String.t(), source: :hand | :seed}}
  def all, do: @examples

  @doc "The example record for one tag, or nil."
  @spec get(String.t()) :: %{code: String.t(), source: :hand | :seed} | nil
  def get(name) when is_binary(name), do: Map.get(@examples, name)

  @doc "Tag names whose example is hand-polished."
  @spec hand_polished() :: [String.t()]
  def hand_polished,
    do: for({n, %{source: :hand}} <- @examples, do: n) |> Enum.sort()

  @doc """
  The example as a standalone, validatable document: wrapped in a minimal
  `<sem-enhanced-document>` unless it already carries the root.
  """
  @spec as_document(String.t()) :: String.t()
  def as_document(code) do
    body =
      if String.contains?(code, "<sem-enhanced-document"),
        do: code,
        else: "<sem-enhanced-document>\n" <> code <> "\n</sem-enhanced-document>"

    """
    <!DOCTYPE html>
    <html lang="en" data-sem-theme="minimal-tech-light">
    <head><meta charset="utf-8"><title>SemText — Claude example</title></head>
    <body>
    #{body}
    </body>
    </html>
    """
  end
end
