defmodule Semtext.Reference.Bundles do
  @moduledoc """
  Shipped-runtime provenance per tag, compile-time-loaded from
  `priv/data/bundles.json`.

  The JSON is generated by `scripts/build-bundle-map.mjs` from the built
  artefacts in `public/semtext/` (which file provides the tag: the lazy
  loader and its chunk, the fallback enhancement tier, the theme CSS alone,
  or nothing) — regenerate after every `/semtext/` sync, exactly as the
  file's header demands. Never hand-edit either side.

  Shape (atom-keyed, `nil` for absent optional fields):

      %{
        shipped: true,
        bundles: [%{file: "semtext-lazy.js", detail: "loads chunks/x.js",
                    chunk: "chunks/x.js"}],
        shared_with: nil | "sem-note",
        css_only: false,
        note: nil
      }

  `:css_only` marks elements that are zero-JS by contract and painted by the
  shipped theme CSS — derived from the CSS selectors upstream, never a hand
  list.
  """

  # ————— compile-time normalization —————
  # Nested helper module: module-body attributes cannot call the enclosing
  # module's own functions; cross-module calls compile (and run at compile
  # time, embedding the result).

  defmodule Norm do
    @moduledoc false

    def normalize(t) do
      %{
        shipped: t["shipped"] == true,
        bundles:
          Enum.map(t["bundles"] || [], fn b ->
            %{file: b["file"], detail: b["detail"] || "", chunk: b["chunk"]}
          end),
        shared_with: t["sharedWith"],
        css_only: t["cssOnly"] == true,
        note: t["note"]
      }
    end
  end

  @external_resource path = Path.expand("../../../priv/data/bundles.json", __DIR__)
  {:ok, decoded} = path |> File.read!() |> Jason.decode()

  @tags Map.new(decoded["tags"], fn {name, t} -> {name, Norm.normalize(t)} end)
  @alias_runtime Map.new(decoded["aliasRuntime"] || [], fn {k, v} -> {String.to_atom(k), v} end)

  @doc "The bundle record for one tag, or nil when the map predates it."
  @spec for_tag(String.t()) :: map() | nil
  def for_tag(name) when is_binary(name), do: Map.get(@tags, name)

  @doc "Every mapped tag name (superset of the inventory: NPL tags included)."
  @spec tag_names() :: [String.t()]
  def tag_names, do: Map.keys(@tags)

  @doc """
  Class-form alias wiring: the one extra bundle file a namespace's class-form
  examples need beyond their tag's own runtime (a `div.sem-<tag>` host only
  enhances under the full bundle). Empty map until that file ships.
  """
  @spec alias_runtime() :: %{optional(atom()) => String.t()}
  def alias_runtime, do: @alias_runtime
end
